import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const source=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'github-supply-chain-review-')));
const repo=path.join(temp,'demo with spaces');
fs.cpSync(source,repo,{recursive:true,filter:file=>!['.git','work','output','node_modules'].some(x=>path.relative(source,file).split(path.sep).includes(x))});
const env={PATH:`${path.dirname(process.execPath)}:/usr/bin:/bin`,DEMO_CANARY:'PARENT_VALUE_MUST_NOT_LEAK'};
function run(file,arg,expected=0) {
  const r=spawnSync(process.execPath,[`scripts/${file}.mjs`,arg],{cwd:repo,env,encoding:'utf8',timeout:90000});
  assert(!r.error&&!r.signal,`${file}: abnormal termination`);
  assert.equal(r.status,expected,r.stdout+r.stderr);
  return r;
}
const result=mode=>JSON.parse(fs.readFileSync(path.join(repo,`output/${mode}/evidence/result.json`)));
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const lock=sha(path.join(repo,'package-lock.json'));
const reviewed=sha(path.join(repo,'approved/contributor-card-1.0.0.tgz'));
const checks=[];
for(const mode of ['baseline','unsafe','protected']) {
  run('ci',mode); assert.equal(result(mode).outcome,'trusted-release');
  assert(!result(mode).fakeTokenCaptured && result(mode).delivered);
}
checks.push('Approved dependency passes all three actual builds');
run('fixture','attack');
const changed=sha(path.join(repo,'packages/contributor-card-1.0.0.tgz'));
assert.notEqual(changed,reviewed); assert.equal(sha(path.join(repo,'package-lock.json')),lock);
run('ci','unsafe');
assert.equal(result('unsafe').outcome,'changed-release');
assert(result('unsafe').fakeTokenCaptured && result('unsafe').delivered);
assert.equal(fs.readFileSync(path.join(repo,'work/unsafe/captured-canary.txt'),'utf8'),'DEMO_ONLY_NOT_A_REAL_CREDENTIAL\n');
const html=fs.readFileSync(path.join(repo,'output/unsafe/site/index.html'),'utf8');
assert(html.includes('A dependency changed this page') && !html.includes('PARENT_VALUE_MUST_NOT_LEAK'));
checks.push('Unsafe install executes authored hook and produces the changed HTML');
run('ci','protected',1);
assert.equal(result('protected').outcome,'blocked'); assert.match(result('protected').reason,/EINTEGRITY/);
assert(!result('protected').hookRan && !result('protected').buildStarted && !result('protected').delivered);
assert(!fs.existsSync(path.join(repo,'output/protected/site')));
assert(!fs.existsSync(path.join(repo,'work/protected/captured-canary.txt')));
assert.equal(sha(path.join(repo,'work/protected/app/package-lock.json')),lock);
assert.equal(sha(path.join(repo,'work/protected/app/packages/contributor-card-1.0.0.tgz')),changed);
checks.push('Same changed archive fails with original lock before hook/build/delivery');
run('ci','baseline'); assert.equal(result('baseline').outcome,'trusted-release');
checks.push('Approved control remains independent of the changed candidate');
run('fixture','restore'); run('ci','protected');
assert.equal(result('protected').outcome,'trusted-release'); assert.equal(sha(path.join(repo,'packages/contributor-card-1.0.0.tgz')),reviewed);
checks.push('Restored reviewed bytes pass the protected install');
run('fixture','attack');
const direct=spawnSync(process.execPath,['vendor/contributor-card/postinstall.cjs'],{cwd:repo,env:{...env,DEMO_CANARY:'DEMO_ONLY_NOT_A_REAL_CREDENTIAL',DEMO_WORK_ROOT:path.join(repo,'work/unsafe')},encoding:'utf8'});
assert.notEqual(direct.status,0);
checks.push('Direct source-hook execution is refused');
const sentinel=path.join(temp,'external-sentinel'); fs.writeFileSync(sentinel,'unchanged');
const candidate=path.join(repo,'packages/contributor-card-1.0.0.tgz'); fs.unlinkSync(candidate); fs.symlinkSync(sentinel,candidate);
run('fixture','restore',1); assert.equal(fs.readFileSync(sentinel,'utf8'),'unchanged'); fs.unlinkSync(candidate);
checks.push('Fixture archive symlink cannot overwrite an external file');
const approvedSource=path.join(repo,'approved/source'); fs.rmSync(approvedSource,{recursive:true}); fs.symlinkSync(temp,approvedSource);
run('fixture','init',1); assert.equal(fs.readFileSync(sentinel,'utf8'),'unchanged');
checks.push('Redirected approved-source directory is refused');
console.log(checks.map(x=>`PASS ${x}`).join('\n'));
console.log(`All ${checks.length} checks passed. Disposable evidence: ${temp}`);
